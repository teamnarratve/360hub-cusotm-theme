import * as si from 'simple-icons';
import { writeFileSync } from 'node:fs';

const map = { instagram: 'siInstagram', tiktok: 'siTiktok', facebook: 'siFacebook', x: 'siX', youtube: 'siYoutube', snapchat: 'siSnapchat', whatsapp: 'siWhatsapp' };
let php = "<?php\n/**\n * Brand icon paths from Simple Icons (CC0 1.0, https://simpleicons.org).\n * Generated by tools/gen-social-icons.mjs — do not edit.\n *\n * @package The360Hub\n */\n\ndefined( 'ABSPATH' ) || exit;\n\nreturn array(\n";
for (const [key, name] of Object.entries(map)) {
	php += `\t'${key}' => '${si[name].path}',\n`;
}
php += ");\n";
writeFileSync('the360hub/inc/core/social-icons.php', php);
console.log('social icons:', Object.keys(map).join(', '));
